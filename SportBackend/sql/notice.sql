-- 通知表（广播通知，一条消息发给所有人）
CREATE TABLE IF NOT EXISTS notice (
    id BIGINT AUTO_INCREMENT PRIMARY KEY COMMENT '通知ID',
    sports_meeting_id BIGINT DEFAULT NULL COMMENT '所属运动会ID（null表示全局公告）',
    title VARCHAR(200) NOT NULL COMMENT '通知标题',
    content TEXT NOT NULL COMMENT '通知内容',
    file_url VARCHAR(500) DEFAULT NULL COMMENT '附件URL（华为云OBS）',
    file_name VARCHAR(200) DEFAULT NULL COMMENT '附件原始文件名',
    create_time DATETIME DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
    update_time DATETIME DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '更新时间'
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='通知表';

-- 用户通知关联表（记录每个用户的已读状态）
CREATE TABLE IF NOT EXISTS user_notice (
    id BIGINT AUTO_INCREMENT PRIMARY KEY COMMENT 'ID',
    notice_id BIGINT NOT NULL COMMENT '通知ID',
    user_id BIGINT NOT NULL COMMENT '用户ID',
    is_read TINYINT DEFAULT 0 COMMENT '是否已读：0-未读，1-已读',
    read_time DATETIME DEFAULT NULL COMMENT '已读时间',
    create_time DATETIME DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间'
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='用户通知关联表';
